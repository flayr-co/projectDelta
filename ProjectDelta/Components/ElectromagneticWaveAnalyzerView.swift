    // MARK: - Premium Card Container
struct PremiumCard<Content: View>: View {
    var title: String? = nil
    var icon: String? = nil
    var baseColor: Color
    var gradientColors: [Color]
    var stretchVertically: Bool = false
    var isWide: Bool = false
    @ViewBuilder var content: () -> Content
    
    var body: some View {
        VStack(alignment: .leading, spacing: isWide ? 16 : 12) {
            if let title = title, let icon = icon {
                HStack(spacing: 8) {
                    Image(systemName: icon)
                        .font((isWide ? Font.title2 : Font.title3).weight(.semibold))
                        .foregroundStyle(LinearGradient(colors: gradientColors, startPoint: .topLeading, endPoint: .bottomTrailing))
                    Text(title)
                        .font((isWide ? Font.title2 : Font.title3).weight(.semibold))
                        .foregroundStyle(.primary)
                }
                Divider().opacity(0.5)
            }
            
            content()
                .frame(maxWidth: .infinity, alignment: .topLeading)
            
            // Forces the VStack to expand to the max height provided by the parent GridRow
            if stretchVertically {
                Spacer(minLength: 0)
            }
        }
        .frame(maxWidth: .infinity, maxHeight: stretchVertically ? .infinity : nil, alignment: .topLeading)
        .padding(isWide ? 24 : 18)
        .background(
            ZStack {
                Rectangle().fill(.regularMaterial)
                LinearGradient(colors: gradientColors, startPoint: .topLeading, endPoint: .bottomTrailing).opacity(0.04)
            }
        )
        .clipShape(RoundedRectangle(cornerRadius: 16, style: .continuous))
        .overlay(
            RoundedRectangle(cornerRadius: 16, style: .continuous)
                .stroke(baseColor.opacity(0.2), lineWidth: 1)
        )
        .shadow(color: baseColor.opacity(0.05), radius: 8, x: 0, y: 4)
    }
}

// MARK: - Dual Field Wave Visualizer (Electric & Magnetic)
struct DualFieldWaveVisualizer: View {
    var frequencyLog: Double
    var gradientColors: [Color]
    
    var body: some View {
        GeometryReader { geometry in
            ZStack {
                // Center propagation axis line
                Path { path in
                    path.move(to: CGPoint(x: 0, y: geometry.size.height / 2))
                    path.addLine(to: CGPoint(x: geometry.size.width, y: geometry.size.height / 2))
                }
                .stroke(Color.secondary.opacity(0.3), style: StrokeStyle(lineWidth: 1, dash: [4, 4]))
                
                // Magnetic Field Wave Path (B - Blue Offset)
                FieldWavePath(frequencyLog: frequencyLog, geometry: geometry, isMagnetic: true)
                    .stroke(LinearGradient(colors: [.blue, .cyan], startPoint: .leading, endPoint: .trailing), style: StrokeStyle(lineWidth: 2, lineCap: .round))
                
                // Electric Field Wave Path (E - Primary Region Gradient)
                FieldWavePath(frequencyLog: frequencyLog, geometry: geometry, isMagnetic: false)
                    .stroke(LinearGradient(colors: gradientColors, startPoint: .leading, endPoint: .trailing), style: StrokeStyle(lineWidth: 3, lineCap: .round))
                    .shadow(color: gradientColors.first!.opacity(0.5), radius: 4)
            }
        }
    }
}

private struct FieldWavePath: Shape {
    var frequencyLog: Double
    var geometry: GeometryProxy
    var isMagnetic: Bool
    
    var animatableData: Double {
        get { frequencyLog }
        set { frequencyLog = newValue }
    }
    
    func path(in rect: CGRect) -> Path {
        var path = Path()
        let width = geometry.size.width
        let height = geometry.size.height
        let midY = height / 2.0
        
        let mappedFrequency = max(1.5, frequencyLog - 2.0)
        let visualWavelength = width / CGFloat(mappedFrequency)
        
        let baseAmplitude = (height / 2.5) * (1.0 - (frequencyLog / 45.0))
        
        path.move(to: CGPoint(x: 0, y: midY))
        
        for x in stride(from: 0, through: width, by: 1) {
            let relativeX = x / visualWavelength
            let sineValue = sin(relativeX * .pi * 2)
            
            if isMagnetic {
                let y = midY + (sineValue * baseAmplitude * 0.45)
                path.addLine(to: CGPoint(x: x, y: y))
            } else {
                let y = midY + (sineValue * baseAmplitude)
                path.addLine(to: CGPoint(x: x, y: y))
            }
        }
        
        return path
    }
}

