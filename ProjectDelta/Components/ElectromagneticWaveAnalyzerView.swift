    private func visibleLightColor(for logValue: Double) -> Color {
        guard logValue >= 14.3 && logValue <= 14.8 else { return .primary }
        let percent = (logValue - 14.3) / 0.5
        let hueValue = percent * 0.75
        return Color(hue: hueValue, saturation: 1.0, brightness: 1.0)
    }
    
